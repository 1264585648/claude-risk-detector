export const BASH_CLI_SCRIPT = [
  '#!/usr/bin/env bash',
  '# [Claude Code 终端环境自检脚本 - macOS / Linux]',
  '# 复制并在 Terminal 中执行',
  '',
  'echo -e "\\033[36m========== Claude Code 终端环境自检 (macOS/Linux) ==========\\033[0m"',
  '',
  '# 1. 检查时区',
  'if command -v timedatectl &>/dev/null; then',
  '    TZ_VAL=$(timedatectl | grep "Time zone" | awk \'{print $3}\')',
  'else',
  '    TZ_VAL=$(date +%Z)',
  'fi',
  'echo "[1] 系统时区: $TZ_VAL"',
  'if echo "$TZ_VAL" | grep -Ei "CST|Shanghai|Chongqing|Hong_Kong|Taipei" >/dev/null; then',
  '    echo -e "    \\033[33m[!] 建议优化：检测到东八区时区，建议在终端执行: export TZ=\'America/New_York\'\\033[0m"',
  'else',
  '    echo -e "    \\033[32m[OK] 时区配置正常\\033[0m"',
  'fi',
  '',
  '# 2. 检查 Git 邮箱',
  'GIT_EMAIL=$(git config --get user.email 2>/dev/null || echo "")',
  'echo "[2] Git 配置邮箱: $GIT_EMAIL"',
  'if echo "$GIT_EMAIL" | grep -Ei "@(qq|163|126|foxmail|aliyun|sina)\\.com" >/dev/null; then',
  '    echo -e "    \\033[33m[!] 建议优化：检测到国内邮箱服务商，建议配置 GitHub 官方隐私邮箱或海外邮箱\\033[0m"',
  'else',
  '    echo -e "    \\033[32m[OK] Git 邮箱配置正常\\033[0m"',
  'fi',
  '',
  '# 3. 检查系统语言',
  'echo "[3] 系统语言 LANG: $LANG"',
  'if echo "$LANG" | grep -i "zh_CN" >/dev/null; then',
  '    echo -e "    \\033[33m[!] 建议优化：终端语言为 zh_CN，建议执行: export LANG=en_US.UTF-8\\033[0m"',
  'fi',
  '',
  'echo -e "\\033[36m========== 自检结束 ==========\\033[0m"'
].join('\n');

